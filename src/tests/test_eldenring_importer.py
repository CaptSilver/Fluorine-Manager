def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def tree(root: Path) -> dict:
    return {
        p.relative_to(root).as_posix(): (p.stat().st_size, sha(p)) for p in sorted(root.rglob("*")) if p.is_file()
    }


def mod_table(mod_id: str, **extra) -> str:
    fields = {"id": mod_id, "install": INSTALL[mod_id], **extra}
    return "[[mods]]\n" + "".join(f"{k} = {json.dumps(v)}\n" for k, v in fields.items())


def build_erm(root: Path) -> None:
    (root / "vendor").mkdir(parents=True)
    (root / "profiles").mkdir()
    lock = ["# Generated by erm.\n"]
    for mod_id, asset in ASSETS.items():
        support.write_zip(root / "vendor" / asset, ARCHIVES[mod_id])
        source = "github" if mod_id == "erd-tools" else "nexus"
        file_id = "" if mod_id in ("item-enemy-randomizer", "other-ancestor") else f'file_id = "{abs(hash(mod_id)) % 9000 + 1000}"\n'
        lock.append(
            f'\n[{mod_id}]\nversion = "1.0"\n{file_id}asset = {json.dumps(asset)}\n'
            f'sha256 = "{sha(root / "vendor" / asset)}"\nsource = "{source}"\n'
        )
    (root / "mods.lock.toml").write_text("".join(lock))
    installed = {"_build": {**BUILD, "regulation_sha": hashlib.sha256(_regulation_blob("11711000")).hexdigest()}}
    for mod_id, files in FILES.items():
        installed[mod_id] = {"archive": ASSETS[mod_id], "files": files, "install": INSTALL[mod_id], "version": "1.0"}
    (root / "installed.json").write_text(json.dumps(installed))
    (root / "profiles/base.toml").write_text(
        'name = "base"\n'
        + mod_table("seamless-coop", source="nexus", nexus_id=510)
        + mod_table("elden-mod-loader", source="nexus", nexus_id=117)
        + mod_table("adjust-the-fov", source="nexus", nexus_id=325)
        + mod_table("erdyes", source="nexus", nexus_id=6927)
        + mod_table("map-for-goblins", source="nexus", nexus_id=10062)
        + mod_table("erd-tools", source="github", repo_id=514620889)
        + mod_table("me3-host", source="github", repo_id=540883721)
    )
    (root / "profiles/full.toml").write_text(
        'name = "full"\nincludes = ["base"]\n'
        + mod_table("forever-buffs", source="nexus", nexus_id=8644, subdir="Files/mod")
        + mod_table("clevers-moveset", source="nexus", nexus_id=1928)
        + '\n[[merges]]\npath = "regulation.bin"\nstrategy = "param-rows"\nmods = ["clevers-moveset", "forever-buffs"]\n'
        'prefer = "clevers-moveset"\nvanilla = { mod = "item-enemy-randomizer", member = "Rand/regulation.bin" }\n'
        '\n[[prunes]]\nmod = "forever-buffs"\npaths = ["dead.bin"]\n'
        '\n[[renames]]\nmod = "clevers-moveset"\n[renames.paths]\n"msg/engUS/a.dcx" = "msg/engus/a.dcx"\n'
    )
    # The profile that carries the ancestor's Nexus id is never imported.
    (root / "profiles/randomizer.toml").write_text(
        'name = "randomizer"\n' + mod_table("item-enemy-randomizer", source="nexus", nexus_id=428)
    )
    (root / "tools/baselines").mkdir(parents=True)
    (root / "tools/baselines/regulation-11711000.bin").write_bytes(_regulation_blob("11711000"))
    (root / "secrets.env").write_text("# secrets\nCOOP_PASSWORD=hunter2\nNEXUS_API_KEY=\n")


class ImporterCase(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.erm = self.tmp / "erm"
        build_erm(self.erm)
        self.profiles_dir = self.tmp / "elsewhere/profiles"
        self.organizer = support.FakeOrganizer(self.tmp / "instance", profiles_dir=self.profiles_dir)
        self.modlist = self.organizer.mod_list
        self.paths = state.InstancePaths(self.organizer)
        self.save_dir = self.tmp / "steam/Roaming/EldenRing/7656"
        self.save_dir.mkdir(parents=True)
        self.game = self.tmp / "steam/Game"
        self.game.mkdir()
        (self.game / "eldenring.exe").write_bytes(b"MZ")
        self.modlist.installed_callbacks.append(kinds.record_on_install)
        os.environ.setdefault("TZ", "UTC")

    def run_import(self, **kwargs) -> importer.Report:
        kwargs.setdefault("save_dir", self.save_dir)
        kwargs.setdefault("guessed", lambda name: name)
        kwargs.setdefault("stamp", "20261014T010203000001Z")
        return importer.run(self.organizer, self.erm, **kwargs)

    def mod(self, name):
        found = self.modlist.getMod(name)
        self.assertIsNotNone(found, f"{name} is not installed")
        return found

    def setting(self, name, key):
        return self.mod(name).pluginSetting(kinds.PLUGIN, key)

    def profile_dir(self, name) -> Path:
        return self.profiles_dir / name

    def modlist_lines(self, name) -> list[str]:
        return (self.profile_dir(name) / "modlist.txt").read_bytes().decode().split("\r\n")


