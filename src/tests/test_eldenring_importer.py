class NothingElseIsTouchedTests(ImporterCase):
    def test_the_erm_checkout_the_game_folder_and_the_save_folder_are_byte_identical(self) -> None:
        (self.save_dir / "ER0000.sl2").write_bytes(b"vanilla")
        (self.save_dir / "ER0000.co2").write_bytes(b"coop")
        before = (tree(self.erm), tree(self.game), tree(self.save_dir))
        self.run_import()
        self.assertEqual((tree(self.erm), tree(self.game), tree(self.save_dir)), before)

    def test_a_second_run_changes_nothing(self) -> None:
        (self.save_dir / "ER0000.sl2").write_bytes(b"vanilla")
        self.run_import()
        instance_before = tree(self.organizer.base)
        profiles_before = tree(self.profiles_dir)
        installs = len(self.organizer.install_calls)
        report = self.run_import(stamp="20261014T999999000001Z")
        self.assertEqual(len(self.organizer.install_calls), installs)
        self.assertEqual(tree(self.profiles_dir), profiles_before)
        after = tree(self.organizer.base)
        new = {k for k in after if k not in instance_before}
        self.assertTrue(all("save-backups" in k for k in new), new)
        self.assertEqual({k: v for k, v in after.items() if k in instance_before}, instance_before)
        self.assertTrue(any("skipped" in t for _, t in report.lines))

    def test_a_run_that_was_cut_off_before_the_profiles_resumes_without_installing_again(self) -> None:
        self.run_import()
        installs = len(self.organizer.install_calls)
        shutil.rmtree(self.profiles_dir)
        report = self.run_import()
        self.assertEqual(len(self.organizer.install_calls), installs)
        self.assertTrue(any("already installed" in t for _, t in report.lines))
        self.assertTrue((self.profiles_dir / "full/modlist.txt").is_file())


