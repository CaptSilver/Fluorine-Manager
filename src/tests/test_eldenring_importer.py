class SaveBackupTests(ImporterCase):
    def test_every_save_file_is_copied_with_its_name_and_the_stamp_and_none_is_moved(self) -> None:
        files = {"ER0000.sl2": b"vanilla", "ER0000.sl2.bak": b"vanilla bak", "ER0000.co2": b"coop", "ER0000_modded": b"mod"}
        for name, data in files.items():
            (self.save_dir / name).write_bytes(data)
        before = tree(self.save_dir)
        self.run_import()
        self.assertEqual(tree(self.save_dir), before)
        for name, data in files.items():
            copy = self.paths.save_backups / f"{name}.20261014T010203000001Z-pre-erm-import"
            self.assertEqual(copy.read_bytes(), data, name)

    def test_no_save_files_is_a_note_not_an_error(self) -> None:
        report = self.run_import()
        self.assertTrue(any("nothing to back up" in text for _, text in report.lines))

    def test_a_copy_that_does_not_match_stops_the_import_before_anything_else(self) -> None:
        (self.save_dir / "ER0000.sl2").write_bytes(b"vanilla")
        with mock.patch.object(importer.ermsaves, "backup_save", side_effect=lambda src, dst, **kw: self._bad_copy(dst)):
            with self.assertRaises(importer.ImportStopped):
                self.run_import()
        self.assertEqual(self.modlist.mods, {})

    def _bad_copy(self, dst):
        dst.mkdir(parents=True, exist_ok=True)
        bad = dst / "bad"
        bad.write_bytes(b"different")
        return bad


class BuildKnowledgeTests(ImporterCase):
    def test_the_stamp_and_the_baseline_are_carried_across(self) -> None:
        self.run_import()
