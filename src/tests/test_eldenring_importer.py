    def test_a_multi_dll_native_keeps_native_and_its_dll_after_the_callbacks(self) -> None:
        # Two DLLs make the wrapper folder unknown, so the unforced rule
        # unwraps it; the `dll` field still finds its file by its shorter tail.
        ARCHIVES_ = {"MultiMod/main.dll": "MZ", "MultiMod/helper.dll": "MZ"}
        support.write_zip(self.erm / "vendor" / ASSETS["map-for-goblins"], ARCHIVES_)
        lock = (self.erm / "mods.lock.toml").read_text()
        old = sha_of_lock(lock, "map-for-goblins")
        (self.erm / "mods.lock.toml").write_text(lock.replace(old, sha(self.erm / "vendor" / ASSETS["map-for-goblins"])))
        (self.erm / "profiles/base.toml").write_text(
            (self.erm / "profiles/base.toml").read_text().replace(
                'id = "map-for-goblins"', 'id = "map-for-goblins"\ndll = "MultiMod/main.dll"'
            )
        )
        self.run_import()
        self.modlist.flush_installed()
        self.assertEqual(self.setting("map-for-goblins", "kind"), "native")
        self.assertEqual(self.setting("map-for-goblins", "native_dll"), "main.dll")

